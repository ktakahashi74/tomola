import fs from "node:fs";
import path from "node:path";
import { expect, type Page } from "@playwright/test";
import { test } from "./editor-fixture";
import { LANG_LABELS } from "../app/lib/languages";
import { enMessages as en, jaMessages as ja, formatMessage, openPostSettings, openUserMenu, state, useMember, waitForFormReady, waitForClientRoute } from "./helpers";

const body = (page: Page) => page.locator('textarea[name="body"]');
const settings = (page: Page) => page.locator("[data-post-settings]");

for (const locale of ["en", "ja"] as const) test(`writing summaries identify post and reply languages in ${locale}`, async ({ page }) => {
  const messages = locale === "en" ? en : ja;
  const postLanguage = formatMessage(messages.post_summary_lang, { lang: LANG_LABELS.ja });
  const replyLanguage = formatMessage(messages.reply_summary_lang, { lang: LANG_LABELS.en });
  const summary = () => settings(page).locator(":scope > summary");
  const withChange = (text: string) => `${text}·${messages.post_settings_change}`;
  await page.context().addCookies([{ name: "PARAGLIDE_LOCALE", value: locale, url: state().baseURL }]);
  await useMember(page, `writing_language_${locale}@example.com`, "/t/new");
  await waitForFormReady(page.locator("form", { has: body(page) }));
  await expect(summary()).toHaveText(withChange(messages.post_summary_lang_auto));
  await expect(settings(page)).not.toHaveAttribute("open");
  await openPostSettings(page);
  await page.getByRole("combobox", { name: messages.field_lang, exact: true }).click();
  await page.getByRole("option", { name: LANG_LABELS.ja, exact: true }).click();
  await summary().click();
  await expect(summary()).toHaveText(withChange(postLanguage));
  await expect(settings(page)).not.toHaveAttribute("open");
  await page.locator('input[name="title"]').fill(`Language summary ${locale}`);
  await body(page).fill("Writing whose language is explicit.");
  await expect(page.locator("[data-draft-autosave]")).toHaveAttribute("data-draft-autosave", "saved");
  const id = await page.locator('input[name="fromDraft"]').inputValue();
  await page.goto(`/drafts/${id}`);
  await waitForFormReady(page.locator("form", { has: body(page) }));
  await expect(summary()).toHaveText(withChange(postLanguage));
  await page.getByRole("button", { name: messages.draft_publish, exact: true }).click();
  await expect(page).toHaveURL(/\/t\/\d+\?posted=/);
  const topicPath = new URL(page.url()).pathname;
  await page.goto(topicPath + "/edit");
  await waitForFormReady(page.locator("form", { has: body(page) }));
  await expect(summary()).toHaveText(withChange(postLanguage));
  await page.getByRole("link", { name: messages.cancel, exact: true }).click();
  await expect(page).toHaveURL(new URL(topicPath, state().baseURL).href);
  await expect(summary()).toHaveText(withChange(messages.reply_summary_lang_auto));
  await openPostSettings(page);
  await page.getByRole("combobox", { name: messages.field_lang_reply, exact: true }).click();
  await page.getByRole("option", { name: LANG_LABELS.en, exact: true }).click();
  await summary().click();
  await expect(summary()).toHaveText(withChange(replyLanguage));
  await expect(settings(page)).not.toHaveAttribute("open");
  await body(page).fill(`An owned reply for the ${locale} summary.`);
  await page.getByRole("button", { name: messages.submit_reply, exact: true }).click();
  await expect(page).toHaveURL(url => /^#c-\d+$/.test(url.hash));
  const replyId = new URL(page.url()).hash.slice(3);
  await page.locator(`#c-${replyId}`).getByRole("link", { name: messages.edit, exact: true }).click();
  await expect(page).toHaveURL(new URL(`/c/${replyId}/edit`, state().baseURL).href);
  await waitForFormReady(page.locator("form", { has: body(page) }));
  await expect(summary()).toHaveText(withChange(replyLanguage));
  await openPostSettings(page);
  await page.getByRole("combobox", { name: messages.field_lang, exact: true }).click();
  await page.getByRole("option", { name: LANG_LABELS.ja, exact: true }).click();
  await summary().click();
  await expect(summary()).toHaveText(withChange(formatMessage(messages.reply_summary_lang, { lang: LANG_LABELS.ja })));
  await expect(settings(page)).not.toHaveAttribute("open");
});

test("an article's usual-language choice shows its translation without changing original-reading preferences", async ({ page }) => {
  const topic = JSON.parse(fs.readFileSync(path.join(state().dir, "writing-language.json"), "utf8")) as { id: number; lang: string; title: string; body: string; reply: { id: number; body: string } };
  await page.context().addCookies([{ name: "PARAGLIDE_LOCALE", value: "en", url: state().baseURL }]);
  await useMember(page, "writing_read_language@example.com", `/t/${topic.id}`);
  const localeBefore = (await page.context().cookies()).filter(cookie => cookie.name === "PARAGLIDE_LOCALE");
  const menu = page.locator("[data-reading-byline] details.reading-lang-menu");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(topic.title);
  for (const language of ["en", "ja", "en"] as const) {
    await menu.locator("summary").click();
    await menu.locator(`a[hreflang="${language}"]`).click();
    await expect(page.getByRole("heading", { level: 1 })).toHaveText(language === "ja" ? topic.title : `[en] ${topic.title}`);
    await expect(page.locator("[data-reading-body]")).toContainText(language === "ja" ? topic.body.split("\n")[0] : `[en] ${topic.body.split("\n")[0]}`);
    await expect(page.locator("html")).toHaveAttribute("lang", "en");
    await expect(page).toHaveURL(url => url.searchParams.get("lang") === language && ["orig", "tr", "old"].every(key => !url.searchParams.getAll(key).includes(String(topic.id))));
  }
  expect((await page.context().cookies()).filter(cookie => cookie.name === "PARAGLIDE_LOCALE")).toEqual(localeBefore);
  await waitForClientRoute(page);
  await (await openUserMenu(page)).getByRole("menuitem", { name: en.nav_language, exact: true }).click();
  await page.getByRole("menuitemradio", { name: LANG_LABELS.ja, exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("lang", "ja");
  await expect(page).toHaveURL(url => !url.searchParams.has("lang") && !url.searchParams.has("rl"));
  await menu.locator("summary").click();
  await menu.locator('a[hreflang="en"]').click();
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(`[en] ${topic.title}`);
  await menu.locator("summary").click();
  await menu.locator('a[hreflang="ja"]').click();
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(topic.title);
  await expect(page).toHaveURL(url => !url.searchParams.has("lang") && !url.searchParams.has("rl") && ["orig", "tr", "old"].every(key => !url.searchParams.has(key)));
  await expect(page.locator(`#c-${topic.reply.id} [data-quote-entry]`)).toHaveText(topic.reply.body);
  const replyLink = page.locator(`#c-${topic.reply.id} a[href*="#c-${topic.reply.id}"]`).first();
  const carried = new URL((await replyLink.getAttribute("href"))!, state().baseURL);
  expect(carried.searchParams.has("lang")).toBe(false);
  expect(carried.searchParams.has("rl")).toBe(false);
  await page.goto("/settings");
  const preferences = page.getByRole("group", { name: ja.onboarding_read_langs });
  for (const language of ["ja", "en"] as const) await expect(preferences.getByRole("checkbox", { name: LANG_LABELS[language], exact: true })).toBeChecked();
});
