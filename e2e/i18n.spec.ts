import { enMessages, formatMessage } from "./helpers";
import fs from "node:fs";
import path from "node:path";
import { expect, type Page } from "@playwright/test";
import { test } from "./editor-fixture";
import { waitForClientRoute, uiMessages, useMember, openUserMenu, clientHeaders, logSize, mailFor, state  } from "./helpers";
import { LANG_LABELS, type Lang } from "../app/lib/languages";

// Nine UI languages: the switcher lists native names; switching to new languages (Français, ไทย, 繁體中文) changes the UI, html lang and login email to that language.
// Strings come from messages/<language>.json generated by pnpm i18n:translate. Use lena, invited by e2e/seed.ts.
const messagesOf = (locale: string): Record<string, string> => {
  const read = (lang: string) => JSON.parse(fs.readFileSync(path.join(process.cwd(), "messages", `${lang}.json`), "utf8")) as Record<string, string>;
  return locale === "en" || locale === "ja" ? read(locale) : { ...read("en"), ...read(locale) };
};
const NAMES = ["日本語", "English", "Français", "Deutsch", "繁體中文", "简体中文", "한국어", "ไทย", "Tiếng Việt"];

test.describe.configure({ mode: "serial" });

let page: Page;
test.beforeAll(async ({ browser }) => {
  const context = await browser.newContext({ extraHTTPHeaders: clientHeaders("10.4.0.1") });
  page = await context.newPage();
});

// Current UI language: the switcher's label is localized and differs by language.
let current = "en";
// Switching before hydration has no effect; retry until it works.
async function switchTo(locale: string) {
  await expect(async () => {
    if (await page.locator("[data-member-menu-trigger]").isVisible()) {
      const menu = await openUserMenu(page);
      await menu.getByRole("menuitem", { name: messagesOf(current).nav_language, exact: true }).click();
      await page.getByRole("menuitemradio", { name: LANG_LABELS[locale as Lang], exact: true }).click();
    } else {
      await page.getByRole("combobox", { name: messagesOf(current).language_select, exact: true }).click();
      await page.getByRole("option", { name: LANG_LABELS[locale as Lang], exact: true }).click();
    }
    await expect(page.locator("html")).toHaveAttribute("lang", locale, { timeout: 5_000 });
  }).toPass({ timeout: 30_000 });
  current = locale;
}

test("a member signs up, and the language switcher lists the nine languages by their own names", async () => {
  await useMember(page, "lena@example.com");
  await openUserMenu(page);
  await page.getByRole("menuitem", { name: messagesOf(current).nav_language, exact: true }).click();
  await expect(page.getByRole("menuitemradio")).toHaveText(NAMES);
  await expect(page.getByRole("menuitemradio")).toHaveCount(9);
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
});

test("switching to French, Thai and Traditional Chinese changes the page, the html lang and keeps the choice on the next page", async () => {
  for (const locale of ["fr", "th", "zh-Hant"]) {
    await switchTo(locale);
    const messages = await uiMessages(page);
    await openUserMenu(page);
    // The drafts link is inside the user menu.
    await expect(page.getByRole("menuitem", { name: messages.nav_drafts, exact: true })).toBeVisible();
    await expect(page.getByRole("link", { name: messages.nav_new_topic, exact: true })).toBeVisible();
    // No English text remains in the navigation.
    await expect(page.getByRole("menuitem", { name: enMessages.nav_drafts, exact: true })).toHaveCount(0);
    // The same language persists on the next page via the cookie.
    await page.goto("/latest");
    await expect(page.locator("html")).toHaveAttribute("lang", locale);
  }
  await switchTo("en");
});

test("the login link mail is written in the language of the page it was asked from", async () => {
  await openUserMenu(page);
  await page.getByRole("menuitem", { name: enMessages.nav_logout }).click();
  await expect(page).toHaveURL(/\/login$/);
  // Check the two source locales; missing translations use English.
  for (const locale of ["ja", "en"]) {
    await page.goto("/login");
    const current = messagesOf((await page.locator("html").getAttribute("lang")) ?? "en");
    if (await page.getByRole("button", { name: current.login_restart, exact: true }).count()) await page.getByRole("button", { name: current.login_restart, exact: true }).click();
    await switchTo(locale);
    const messages = messagesOf(locale);
    await expect(page.getByRole("heading", { name: messages.login_title })).toBeVisible();
    const since = logSize();
    await page.getByLabel(messages.login_email, { exact: true }).fill("lena@example.com");
    await page.getByRole("button", { name: messages.login_submit }).click();
    await expect(page.getByText(messages.login_sent.replace("{email}", "lena@example.com"))).toBeVisible();
    const mail = await mailFor("lena@example.com", since);
    expect(mail.subject).toBe(messages.mail_magic_link_subject);
    const url = mail.text.match(/https?:\/\/[^\s]+\/auth\/confirm\?token=[^\s]+/)?.[0];
    expect(url).toBeDefined();
    const code = mail.text.match(/^\d{3} \d{3}$/m)?.[0];
    expect(code).toBeDefined();
    expect(mail.text).toBe(formatMessage(messages.mail_magic_link_body, { code: code!, url: url!, minutes: 15 }));
  }
});

test("the browser's language decides the first page: Chinese by script and English for a language that is not offered", async ({ browser }) => {
  const cases: Array<[string, string]> = [
    ["zh-TW", "zh-Hant"],
    ["zh-CN", "zh-Hans"],
    ["sv-SE", "en"],
  ];
  for (const [browserLocale, expected] of cases) {
    const context = await browser.newContext({ locale: browserLocale, extraHTTPHeaders: clientHeaders("10.4.0.2") });
    try {
      const p = await context.newPage();
      const errors: string[] = [];
      p.on("console", (msg) => {
        if (msg.type() === "error" || msg.type() === "warning") errors.push(msg.text());
      });
      const res = await p.goto("/login");
      await expect(p.locator("html")).toHaveAttribute("lang", expected);
      await expect(p.getByRole("heading", { name: messagesOf(expected).login_title })).toBeVisible();
      // The server sets no cookie for the interface language (the server decides and the browser reads the <html lang> it rendered; app/lib/http/locale-strategy.ts).
      // (Playwright's response.headers() hides cookie headers; read allHeaders().)
      expect((await res!.allHeaders())["set-cookie"] ?? "").toBe("");
      await waitForClientRoute(p);
      expect(errors.filter((e) => /hydrat/i.test(e)), `hydration warnings for ${browserLocale}`).toEqual([]);
      // Reload preserves the language; the cookie takes precedence.
      await p.reload();
      await expect(p.locator("html")).toHaveAttribute("lang", expected);
    } finally {
      await context.close();
    }
  }
});
