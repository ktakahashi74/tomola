test("reply guidance belongs to callable reply fields and links to the AI explanation", async ({ page, browser }) => {
  await page.context().setExtraHTTPHeaders(clientHeaders("192.0.2.234"));
  await useMember(page, "zcn_flow_owner@example.com", "/v/chat-nushi-browser?lang=en");
  await waitForClientRoute(page);
  await page.getByRole("link", { name: "Orchard evidence", exact: true }).click();
  await waitForClientRoute(page);
  const topic = new URL(page.url()).pathname;
  const help = page.locator("#reply [data-nushi-mention-help]");
  await expect(help).toBeVisible();
  await expect(help).toHaveClass(/ui-help/);
  await expect(help.getByRole("link")).toHaveAttribute("href", "/ai-use#nushi");
  const field = page.locator('#reply textarea[name="body"]');
  await field.fill("@nushi orchard");
  await expect(page.getByText(en.nushi_call_notice, { exact: true })).toBeVisible();
  await expect(help).toHaveCount(0);
  await field.fill("");
  await expect(help).toBeVisible();
  await page.getByLabel(en.nushi_disable_topic, { exact: true }).check();
  await page.locator('form:has(input[value="topic"])').getByRole("button").click();
  await expect(help).toHaveCount(0);
  await page.getByLabel(en.nushi_disable_topic, { exact: true }).uncheck();
  await page.locator('form:has(input[value="topic"])').getByRole("button").click();
  await expect(help).toBeVisible();
  const guest = await browser.newContext({ baseURL: state().baseURL, ignoreHTTPSErrors: true, extraHTTPHeaders: clientHeaders("192.0.2.235") });
  try {
    const reader = await guest.newPage();
    await reader.goto(`${topic}?lang=en`);
    await expect(reader.locator("[data-nushi-mention-help]")).toHaveCount(0);
  } finally { await guest.close(); }
  await page.goto("/v/chat-nushi-browser?lang=en");
  const management = page.locator("#village-management");
  await management.locator(":scope > summary").click();
  const setting = management.locator('form[action="/nushi/action"]');
  await setting.locator('input[name="enabled"]').uncheck();
  await setting.getByRole("button").click();
  await waitForClientRoute(page);
  await page.goto(`${topic}?lang=en`);
  await waitForClientRoute(page);
  await expect(help).toHaveCount(0);
  await page.goto("/v/chat-nushi-browser?lang=en");
  await management.locator(":scope > summary").click();
  await setting.locator('input[name="enabled"]').check();
  await setting.getByRole("button").click();
  await waitForClientRoute(page);
  await page.goto("/t/new?village=chat-nushi-browser&lang=en");
  await waitForClientRoute(page);
  await expect(page.locator("[data-nushi-mention-help]")).toHaveCount(0);
});

test("Nushi calls produce sourced public AI replies with independent reader and owner controls", async ({ page, browser }) => {
  test.setTimeout(240_000);
  await page.context().setExtraHTTPHeaders(clientHeaders("192.0.2.218"));
  await useMember(page, "znushi_flow_owner@example.com", "/settings?lang=en#settings-nushi");
  await waitForClientRoute(page);
  const settings = page.locator("#settings-nushi");
  await settings.getByLabel(en.nushi_enable, { exact: true }).check();
  await settings.locator('form:has(input[name="villageId"])').getByRole("button").click();
  await expect(settings.getByLabel(en.nushi_enable, { exact: true })).toBeChecked();
  await page.goto("/t/new?lang=en");
  await waitForClientRoute(page);
  await page.getByLabel(en.field_body, { exact: true }).fill("Orchard source for a public AI reply. The growers disagree about the planting date.");
  await page.getByRole("button", { name: en.submit_post, exact: true }).click();
  await expect(page).toHaveURL(/\/t\/\d+/);
  const topic = new URL(page.url()).pathname;
  const callerContext = await browser.newContext({ baseURL: state().baseURL, ignoreHTTPSErrors: true, serviceWorkers: "block", extraHTTPHeaders: clientHeaders("192.0.2.219") });
  const guestContext = await browser.newContext({ baseURL: state().baseURL, ignoreHTTPSErrors: true, serviceWorkers: "block", extraHTTPHeaders: clientHeaders("192.0.2.220") });
  try {
    const caller = await callerContext.newPage();
    await caller.setViewportSize({ width: 390, height: 844 });
    await useMember(caller, "znushi_flow_caller@example.com", `${topic}?lang=en`);
    await waitForClientRoute(caller);
    const body = caller.locator('#reply textarea[name="body"]');
    await body.fill("@nu");
    await expect(caller.getByRole("option").filter({ hasText: "@nushi" })).toBeVisible();
    await caller.getByRole("option").filter({ hasText: "@nushi" }).click();
    await body.fill("@nushi orchard planting date");
    await expect(caller.getByText(en.nushi_call_notice, { exact: true })).toBeVisible();
    await expect(caller.locator('input[name="suppressNushi"]')).toHaveCount(0);
    let releaseStatus = false, statusReads = 0;
    await caller.route("**/nushi/request/*/status", async route => {
      statusReads++;
      const response = await route.fetch();
      if (!response.ok()) { await route.fulfill({ response }); return; }
      const data = await response.json();
      expect(Object.keys(data)).toEqual(["state"]);
      await route.fulfill({ response, json: releaseStatus ? data : { state: "pending" } });
    });
    await caller.getByRole("button", { name: en.submit_reply, exact: true }).click();
    await expect(caller.locator("#replies")).toContainText("@nushi orchard planting date");
    await expectNushiPending(caller, caller.locator("[data-nushi-status]").filter({ hasText: en.nushi_pending }));
    await expect.poll(() => statusReads).toBeGreaterThan(0);
    await caller.evaluate(() => { Object.defineProperty(document, "hidden", { configurable: true, get: () => true }); document.dispatchEvent(new Event("visibilitychange")); });
    const readsBeforeHidden = statusReads;
    await caller.clock.install();
    await caller.clock.fastForward(6 * 60_000);
    expect(statusReads).toBe(readsBeforeHidden);
    releaseStatus = true;
    await caller.evaluate(() => { Object.defineProperty(document, "hidden", { configurable: true, get: () => false }); document.dispatchEvent(new Event("visibilitychange")); });
    await expect.poll(() => statusReads, { timeout: 1500 }).toBe(readsBeforeHidden + 1);
    await expect(caller.locator("[data-nushi-answer]")).toHaveCount(1, { timeout: 120_000 });
    await expect(caller.locator("[data-nushi-status]")).toHaveCount(0);
    const answer = caller.locator("[data-nushi-answer]");
    await expect(answer).toContainText("znushi_flow_caller");
    await expect(answer).toContainText(en.nushi_personal_notice);
    await expect(answer.locator("blockquote")).not.toHaveCount(0);
    expect(await caller.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const answerId = (await answer.getAttribute("id"))!.replace("nushi-", "");
    await answer.getByRole("link", { name: en.reply_to_button, exact: true }).click();
    await expect(caller.locator('input[name="nushiParentId"]')).toHaveValue(answerId);
    await body.fill("The orchard source needs its seasonal context.");
    await caller.getByRole("button", { name: en.submit_reply, exact: true }).click();
    await expect(caller.locator("#replies")).toContainText("The orchard source needs its seasonal context.");
    const errorForm = caller.locator('[data-nushi-answer] form:has(input[value="error"])');
    await errorForm.locator("..").locator("summary").click();
    await errorForm.locator('select[name="reason"]').selectOption("lost_context");
    await errorForm.locator('textarea[name="note"]').fill("Please check the seasonal context of the orchard quotation.");
    await errorForm.locator('input[name="consent"]').check();
    await errorForm.getByRole("button", { name: en.nushi_report_error, exact: true }).click();
    await expect(caller).toHaveURL(new RegExp(`/nushi/${answerId}$`));
    await expect(caller.locator("[data-nushi-answer]")).toHaveCount(1);
    await caller.goto("/nushi/reports?lang=en");
    await expect(caller.getByRole("heading", { name: en.nushi_report_status, exact: true })).toBeVisible();
    await expect(caller.getByText("Please check the seasonal context of the orchard quotation.", { exact: true })).toBeVisible();
    await caller.goto(`${topic}?lang=en`);
    const guest = await guestContext.newPage();
    const response = await guest.goto(`${topic}?lang=en`);
    expect(response?.headers()["cache-control"]).toBe("private, no-store");
    expect((await guest.request.get(`${topic}.data?lang=en`)).headers()["cache-control"]).toBe("private, no-store");
    await expect(guest.locator("[data-nushi-answer]")).toHaveCount(1);
    const markdown = await guest.request.get(`${topic}.md?lang=en`);
    expect(await markdown.text()).toContain("author_kind: ai");
    const json = await guest.request.get(`/nushi/${answerId}.json?lang=en`);
    expect((await json.json()).authorKind).toBe("ai");
    await guest.getByLabel(en.nushi_hide, { exact: true }).check();
    await guest.locator('form:has(input[value="visitor-hide"])').getByRole("button").click();
    await expect(guest.locator("[data-nushi-hidden]")).toHaveCount(1);
    await expect(caller.locator("[data-nushi-answer]")).toHaveCount(1);
    await page.goto(`${topic}?lang=en`);
    await page.getByLabel(en.nushi_disable_topic, { exact: true }).check();
    await page.locator('form:has(input[value="topic"])').getByRole("button").click();
    await expect(page.locator("[data-nushi-hidden]")).toHaveCount(1);
    await caller.reload();
    await expect(caller.locator("[data-nushi-answer]")).toHaveCount(0);
    await expect(caller.locator("[data-nushi-hidden]")).toHaveCount(1);
    const withdrawn = await guest.request.get(`/nushi/${answerId}.json?lang=en`);
    const data = await withdrawn.json(); expect(data.hidden).toBe(true); expect(data).not.toHaveProperty("answer");
  } finally { await callerContext.close(); await guestContext.close(); }
});

test("Nushi moderation reports appear in the operator queue and public action log", async ({ page, browser }) => {
  test.setTimeout(180_000);
  await page.context().setExtraHTTPHeaders(clientHeaders("192.0.2.221"));
  await useMember(page, "znushi_mod_owner@example.com", "/settings?lang=en#settings-nushi");
  await waitForClientRoute(page);
  const settings = page.locator("#settings-nushi");
  await settings.getByLabel(en.nushi_enable, { exact: true }).check();
  await settings.locator('form:has(input[name="villageId"])').getByRole("button").click();
  await page.goto("/t/new?lang=en");
  await waitForClientRoute(page);
  await page.getByLabel(en.field_body, { exact: true }).fill("@nushi orchard moderation sources");
  await page.getByRole("button", { name: en.submit_post, exact: true }).click();
  await expect(page).toHaveURL(/\/t\/\d+/);
  const topic = new URL(page.url()).pathname;
  await expect(page.locator("[data-nushi-answer]")).toHaveCount(1, { timeout: 120_000 });
  const answerId = (await page.locator("[data-nushi-answer]").getAttribute("id"))!.replace("nushi-", "");
  const form = page.locator('[data-nushi-answer] form:has(input[value="moderation"])');
  await form.locator("..").locator("summary").click();
  await form.locator('select[name="reason"]').selectOption("other");
  await form.locator('textarea[name="note"]').fill("A public AI source needs operator review.");
  await form.getByRole("button").click();
  await expect(page).toHaveURL(new RegExp(`/nushi/${answerId}$`));
  const operatorContext = await browser.newContext({ baseURL: state().baseURL, ignoreHTTPSErrors: true, serviceWorkers: "block", extraHTTPHeaders: clientHeaders("192.0.2.222") });
  try {
    const operator = await operatorContext.newPage();
    await useMember(operator, "olga@example.com", "/mod?lang=en");
    const queue = operator.getByRole("region", { name: en.nushi_reports, exact: true });
    const queuedReport = queue.locator("article").filter({ has: operator.locator(`a[href="/nushi/${answerId}"]`) }).filter({ hasText: "A public AI source needs operator review." });
    await expect(queuedReport).toHaveCount(1);
    await queuedReport.getByRole("link", { name: en.nushi_reports, exact: true }).click();
    const report = operator.locator('li:has(input[name="reportId"])').filter({ hasText: "A public AI source needs operator review." });
    await report.locator('textarea[name="note"]').fill("Hidden after checking the AI source.");
    await report.getByRole("button", { name: en.nushi_resolve, exact: true }).click();
    await operator.goto("/mod?lang=en");
    await expect(queuedReport).toHaveCount(0);
    await operator.goto("/moderation?lang=en");
    const row = operator.getByRole("row").filter({ hasText: `${en.nushi_name} #${answerId}` });
    await expect(row).toContainText(en.log_action_hide);
    await expect(row).not.toContainText("Hidden after checking the AI source.");
    await page.goto(`${topic}?lang=en`);
    await expect(page.locator("[data-nushi-answer]")).toHaveCount(0);
    await expect(page.locator("[data-nushi-hidden]")).toHaveCount(1);
  } finally { await operatorContext.close(); }
});
